"""Procedural Dependency Constraint (PDC) mutator.

PDC parameters are artifacts that must be generated by an ordered procedure such
as build -> sign -> serialize -> encode.  The mutator executes generated stage
helpers and injects at most one invalid stage so the final request remains close
to a valid construction pipeline.
"""
from __future__ import annotations

import random
from typing import Any, Dict, List, Tuple

from .common import assign_payload, constraint_kind, deep_get, exec_generated_func, fallback_value, load_tools, path_exists


class PDCMutator:
    def __init__(self, method: str, chain: str = "ethereum", invalid_rate: float = 0.5):
        self.method = method
        self.chain = chain
        self.invalid_rate = invalid_rate
        self.history: list[dict[str, Any]] = []

    def mutate(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        for tool in load_tools(self.chain, self.method):
            if constraint_kind(tool) != "PDC":
                continue
            path = tool.get("path") or tool.get("param", "")
            if not path or not path_exists(payload, path):
                continue

            old = deep_get(payload, path)
            new_val, trace = self._mutate_tool(tool)
            if new_val is None:
                new_val = fallback_value(self.chain, "PDC", path)
            if new_val is None:
                continue

            assign_payload(payload, path, new_val)
            self.history.append({"constraint": "PDC", "path": path, "old": old, "new": new_val, "trace": trace})
        return payload

    def _mutate_tool(self, tool: Dict[str, Any]) -> Tuple[Any, List[Dict[str, str]]]:
        variants = tool.get("chain_variants") or tool.get("chain_process") or {}
        imports: List[str] = tool.get("imports", [])
        trace: List[Dict[str, str]] = []
        if not variants:
            mode = "illegal" if tool.get("illegal") and random.random() < self.invalid_rate else "legal"
            return exec_generated_func(tool.get(mode, ""), imports), [{"step": "single", "mode": mode}]

        intermediate = None
        injected_invalid = False
        for step_name, step_variants in variants.items():
            has_illegal = bool(step_variants.get("illegal"))
            want_invalid = (not injected_invalid) and has_illegal and random.random() < self.invalid_rate
            mode = "illegal" if want_invalid else "legal"
            code = step_variants.get(mode) or step_variants.get("legal", "")
            intermediate = exec_generated_func(code, imports, intermediate, pass_arg=intermediate is not None)
            trace.append({"step": str(step_name), "mode": mode})
            if intermediate is None:
                return None, trace
            injected_invalid = injected_invalid or mode == "illegal"
        return intermediate, trace
